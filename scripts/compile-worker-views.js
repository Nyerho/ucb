'use strict';

const fs = require('node:fs');
const path = require('node:path');
const ejs = require('ejs');
const acorn = require('acorn');
const eslintScope = require('eslint-scope');
const globals = require('globals');

const root = path.resolve(__dirname, '..');
const viewsRoot = path.join(root, 'views');
const outputFile = path.join(root, 'lib', 'worker-views.generated.cjs');
const knownGlobals = new Set([
  ...Object.keys(globals.builtin || {}),
  ...Object.keys(globals.browser || {}),
  ...Object.keys(globals.node || {})
]);

function listTemplates(directory) {
  return fs.readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) => {
      const fullPath = path.join(directory, entry.name);
      return entry.isDirectory()
        ? listTemplates(fullPath)
        : entry.isFile() && entry.name.endsWith('.ejs')
          ? [fullPath]
          : [];
    })
    .sort();
}

function localsUsedBy(source, filename) {
  const probe = ejs.compile(source, {
    client: true,
    _with: false,
    filename
  });
  const ast = acorn.parse(`(${probe.toString()})`, {
    ecmaVersion: 'latest',
    sourceType: 'script',
    ranges: true
  });
  const scopes = eslintScope.analyze(ast, {
    ecmaVersion: 2022,
    sourceType: 'script',
    optimistic: true,
    ignoreEval: true
  });
  return [...new Set(scopes.globalScope.through
    .map((reference) => reference.identifier.name)
    .filter((name) => !knownGlobals.has(name)))].sort();
}

const entries = listTemplates(viewsRoot).map((file) => {
  const relative = path.relative(viewsRoot, file).split(path.sep).join('/');
  const viewName = relative.replace(/\.ejs$/, '');
  const workerFilename = `/bundle/${relative}`;
  const source = fs.readFileSync(file, 'utf8');
  const compiled = ejs.compile(source, {
    client: true,
    _with: false,
    destructuredLocals: localsUsedBy(source, workerFilename),
    filename: workerFilename
  });
  const functionSource = compiled.toString().replace(/[ \t]+$/gm, '');
  if (/\bwith\s*\(/.test(functionSource)) {
    throw new Error(`Worker template ${relative} still uses with().`);
  }
  return [viewName, functionSource];
});

if (entries.length === 0) throw new Error(`No EJS templates found under ${viewsRoot}`);

const output = [
  '// Generated by scripts/compile-worker-views.js. Do not edit directly.',
  "'use strict';",
  'module.exports = Object.freeze({',
  ...entries.map(([name, source]) => `  ${JSON.stringify(name)}: ${source},`),
  '});',
  ''
].join('\n');

fs.writeFileSync(outputFile, output);
console.log(`Precompiled ${entries.length} EJS templates to ${path.relative(root, outputFile)}.`);
